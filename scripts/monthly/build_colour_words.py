"""Rebuild config/colour-words.json from the colourways this pipeline collected.

Why a generated list
--------------------
model_grouping.py decides that two listings are one shoe when the only thing
separating their names is a colour. That only works against a vocabulary of
colour words, and no fixed list covers what Korean retailers actually write:
히커리, 팔로미노, 체커보드, 캐슬락, 솔라터보. The retailers themselves supply
it - every value any of them has ever put in a colour field is a colour word
by their own account - so the list is derived from the corpus rather than
guessed at, and rebuilt whenever the corpus grows.

What it refuses to learn
------------------------
The corpus is dirty in three ways, and a word that gets through becomes a
false merge of two different shoes:

* Boilerplate. 29CM and Musinsa paste a standing notice into the colour
  field, so 입고/시기에/바랍니다/상품의/판매하지 were all learned as colours.
  Values go through clean_colour_value first, which cuts the notice off.
* Codes. BGD0, WHGY, UR322CCR81, FW25 - a style or season code is not a
  colour, and as a substring it matches other codes, so merges spread.
  A word has to be all letters.
* Vocabulary that is not colour at all: a brand (푸마), a material (캔버스,
  벨벳), an audience (남성용). Those are listed explicitly below, because
  nothing about their shape distinguishes them.

Frequency is the last gate: a word one listing used once is more likely part
of a model name than a shade.
"""
import json
import os
import re
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from common import atomic_write_json, read_json  # noqa: E402
from footwear_scope import clean_colour_value  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
DATA = os.path.join(ROOT, 'data')
OUT = os.path.join(ROOT, 'config', 'colour-words.json')

STAGING = ('monthly-staging-29cm.json', 'monthly-staging-musinsa.json',
           'monthly-staging-ssense.json', 'monthly-staging-wconcept.json',
           'monthly-staging-newsletter.json')

MIN_OCCURRENCES = 2
MIN_LATIN = 3
MIN_HANGUL = 2
HANGUL = re.compile(r'^[가-힣]+$')
LATIN = re.compile(r'^[a-z]+$')
SPLIT = re.compile(r'[^0-9A-Za-z가-힣]+')

# Words that reach a colour field often enough to pass the frequency gate but
# name something other than a colour. Each one would merge two real models.
NOT_COLOURS = {
    # audience and sizing
    '남성용', '여성용', '남녀공용', '유니섹스', '공용', '키즈', '사이즈',
    # material and construction
    '캔버스', '벨벳', '스웨이드', '가죽', '메쉬', '니트', '헴프', '울', '코듀로이',
    'suede', 'leather', 'canvas', 'mesh', 'knit', 'denim',
    # pattern and finish, which attach to any colour rather than being one
    '체커보드', '레오파드', '도트', '리플렉티브',
    # brands that appear in their own colour fields
    '푸마', '나이키', '아디다스', '뉴발란스', '아식스',
    # season, marketing and leftover sentence fragments
    '신상', '한정', '단독', '정품', '아카이브', '포인트', '와우', '풋볼', '풋웨어',
    '캐리어', '데이츠', '아키오', '배스트', '보그', '리치', '매직베이지', '따라',
    'new', 'colors', 'color', 'three', 'six', 'triple', 'core', 'light', 'dark',
    'bright', 'clear', 'off', 'warm', 'cool', 'dot', 'star', 'empire', 'plaza',
    'land', 'africa', 'english', 'leo', 'magic', 'military', 'safari', 'wonder',
    'wood', 'flux', 'six', 'tea', 'ii', 'dkbl', 'whbk', 'whbr', 'whgy',
    'whpu', 'slx', 'strata', 'tango', 'fandango',
    # Three- and four-letter suffixes that look like a colour abbreviation
    # and are a model or a technology: "Air Max GTX", "Gel-Kayano ATR".
    'gtx', 'dmx', 'atr', 'exo', 'nyc', 'mld', 'arq', 'etr', 'ami', 'rsp',
    'prm', 'txt', 'ltd', 'spt', 'trl', 'nxt', 'evo',
}


def colour_values():
    """Every colour a collector recorded, cleaned of seller boilerplate."""
    values = []
    for name in STAGING:
        payload = read_json(os.path.join(DATA, name), {'items': []})
        for item in payload.get('items') or []:
            cleaned = clean_colour_value(item.get('colorway'))
            if cleaned:
                values.append(cleaned)
    return values


def derive(values):
    counts = Counter()
    for value in values:
        for word in SPLIT.split(value.lower()):
            if not word or word in NOT_COLOURS:
                continue
            if HANGUL.match(word):
                if len(word) >= MIN_HANGUL:
                    counts[word] += 1
            elif LATIN.match(word) and len(word) >= MIN_LATIN:
                counts[word] += 1
    return sorted(w for w, n in counts.items() if n >= MIN_OCCURRENCES)


def main():
    existing = read_json(OUT, {})
    values = colour_values()
    derived = derive(values)
    payload = {
        'schemaVersion': 2,
        'note': ('Generated by scripts/monthly/build_colour_words.py from the colourways the '
                 'collectors recorded. `derived` is every all-letter word seen in at least '
                 f'{MIN_OCCURRENCES} cleaned colour values; `supplement` is hand-maintained and '
                 'covers shades that only ever appear inside product names, which the corpus '
                 'cannot teach. Rebuild after a collection run; do not hand-edit `derived`.'),
        'derived': derived,
        'supplement': sorted(existing.get('supplement') or []),
    }
    atomic_write_json(OUT, payload)
    was = len(existing.get('derived') or [])
    print(f'colour-words.json: {len(derived)} derived words from {len(values)} colour values '
          f'(was {was}).')
    dropped = sorted(set(existing.get('derived') or []) - set(derived))
    if dropped:
        print(f'  no longer learned ({len(dropped)}): {", ".join(dropped[:30])}'
              + (' ...' if len(dropped) > 30 else ''))


if __name__ == '__main__':
    raise SystemExit(main())
