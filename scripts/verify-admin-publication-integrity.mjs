import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const read=async file=>JSON.parse(await fs.readFile(file,'utf8'));
const request=await read('reports/admin-bulk-recheck-request.json');
const baseline=await read(request.baselineDirectory+'/catalog.json');
const current=await read('public/data/catalog.json');
const allowed=new Set(request.targets),index=new Map(current.products.map(p=>[p.id,p]));
assert.equal(index.size,current.products.length,'Duplicate product IDs');
const lost=baseline.products.filter(p=>!index.has(p.id));
const outside=baseline.products.filter(p=>!allowed.has(p.brand)&&JSON.stringify(p)!==JSON.stringify(index.get(p.id)));
const blankPrices=baseline.products.filter(p=>String(p.priceLabel||'').trim()&&!String(index.get(p.id)?.priceLabel||'').trim());
const oldRaw=await read(request.baselineDirectory+'/catalog-source.json');
const raw=await read('data/catalog-source.json');
const rawIds=new Set(raw.products.map(p=>p.id));
assert.equal(rawIds.size,raw.products.length,'Duplicate source product IDs');
assert.ok(oldRaw.products.every(p=>rawIds.has(p.id)),'Existing source product IDs lost');
assert.equal(lost.length,0,'Existing product IDs lost');
assert.equal(outside.length,0,'Unrequested brands changed');
assert.equal(blankPrices.length,0,'Existing nonempty prices erased');
const old=new Set(baseline.products.map(p=>p.id));
const report={checkedAt:new Date().toISOString(),baseline:baseline.products.length,current:current.products.length,added:current.products.filter(p=>!old.has(p.id)).length,lost:0,sourceRecordsLost:0,unrequestedBrandChanges:0,erasedPrices:0,uniqueIds:true};
await fs.writeFile('reports/admin-publication-integrity.json',JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report));
